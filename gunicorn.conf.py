# Render 등에서 `gunicorn app:app` 으로 실행할 때 자동으로 읽히는 설정.
# 인스타그램 게시 중에 Meta 서버가 우리 /media 주소로 사진을 가져가는데,
# 워커가 하나뿐이면 게시 요청을 처리하느라 사진 요청에 답하지 못해 "미디어를 가져올 수 없습니다" 오류가 난다.
# 그래서 스레드를 여러 개 둬서 동시에 처리하게 한다.
workers = 1          # SQLite·메모리 캐시를 한 프로세스에서 공유
threads = 8          # 게시 요청과 사진 요청을 동시에 처리
timeout = 120        # 인스타 사진 처리 대기 시간 여유
